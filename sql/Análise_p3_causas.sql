# Pergunta 3 — Por que as ocorrências acontecem?

**Quais são as causas mais frequentes e quais delas demandam mais tempo para solução?**

## Objetivo

Identificar as principais causas associadas às ocorrências de interrupção e queda de energia na área de atuação da Neoenergia Pernambuco e analisar quais causas estão relacionadas aos maiores tempos de solução.

A análise considera o período de **2021 a 2025**. O tempo total de solução foi calculado pela soma dos tempos de **preparação, deslocamento e execução**.

Para representar a duração típica das ocorrências, foi utilizada principalmente a **mediana**, complementada pelos percentis P75 e P90 para observar ocorrências de maior duração.

---

## Principais resultados

As ocorrências estão fortemente concentradas em três grupos de causa:

* **Próprias do Sistema:** 37,68%
* **Meio Ambiente:** 35,16%
* **Terceiros:** 22,61%

Juntos, esses três grupos representam **95,45% das ocorrências analisadas**.

Entre as causas específicas, destaca-se **Falha de material ou equipamento**, com **270.700 ocorrências (32,36%)**, seguida por:

* **Defeito interno não afetando outras unidades consumidoras:** 90.132 (10,77%)
* **Vento:** 87.255 (10,43%)
* **Árvore ou vegetação:** 74.639 (8,92%)
* **Interferência de terceiros:** 74.567 (8,91%)

Essas cinco causas concentram **71,39% das ocorrências**.

---

## Frequência e duração

A maior frequência de uma causa não significa necessariamente que ela apresente o maior tempo de solução.

Entre os três principais grupos, **Meio Ambiente** apresentou a maior duração mediana, com **303,4 minutos**, aproximadamente 5 horas. Em seguida aparecem **Próprias do Sistema**, com 283,3 minutos, e **Terceiros**, com 217,6 minutos.

Entre as causas com maior frequência, destacam-se:

| Causa                            | Ocorrências | Duração mediana |
| -------------------------------- | ----------: | --------------: |
| Vento                            |      87.255 |       310,7 min |
| Árvore ou vegetação              |      74.639 |       323,5 min |
| Descarga atmosférica             |      50.581 |       361,3 min |
| Falha de material ou equipamento |     270.700 |       283,0 min |
| Interferência de terceiros       |      74.567 |       181,5 min |

Esse resultado mostra que algumas causas combinam **elevado número de ocorrências e maior duração típica**, especialmente as relacionadas ao meio ambiente.

---

## Causas com maior tempo de solução

As maiores durações medianas foram observadas em causas com menor volume de ocorrências.

| Causa                      | Ocorrências |     Mediana |         P90 |
| -------------------------- | ----------: | ----------: | ----------: |
| Erosão                     |         710 | 1.909,2 min | 9.561,7 min |
| Abalroamento               |       2.581 | 1.346,1 min | 4.817,5 min |
| Desligamento por segurança |         675 | 1.054,1 min | 5.690,1 min |
| Inundação                  |         295 |   674,4 min | 5.733,1 min |
| Roubo                      |       5.814 |   505,9 min | 4.347,5 min |

A **erosão** apresentou a maior duração mediana, de aproximadamente **31,8 horas**. Seu P90 chegou a aproximadamente **159,4 horas**, indicando a presença de ocorrências com duração muito superior ao comportamento típico.

O mesmo padrão aparece em outras causas. Em **inundação**, por exemplo, a duração mediana foi de 11,2 horas, enquanto o P90 chegou a aproximadamente 95,6 horas.

Assim, algumas causas apresentam não apenas uma duração típica elevada, mas também uma parcela de ocorrências excepcionalmente prolongadas.

---

## Componentes do tempo de solução

A decomposição do tempo indica que, entre as causas de maior duração, o **tempo de execução** apresenta valores médios elevados.

Na **erosão**, o tempo médio de execução foi de aproximadamente **1.584 minutos**, enquanto no **abalroamento** foi de aproximadamente **1.143 minutos**.

Esse comportamento indica uma associação entre as ocorrências de maior duração e períodos mais prolongados de execução da solução. A análise não permite afirmar causalidade, mas evidencia que a etapa de execução representa uma parcela importante do tempo observado nesses casos.

---

## Síntese

A análise evidencia dois padrões principais.

O primeiro é formado pelas causas de **alta frequência**, especialmente falha de material ou equipamento, vento, árvore ou vegetação e descarga atmosférica. Essas causas representam parcela significativa do volume total de ocorrências.

O segundo reúne causas **menos frequentes, mas associadas a tempos de solução muito elevados**, como erosão, abalroamento, desligamento por segurança e inundação.

Entre esses padrões, algumas causas se destacam por combinar **frequência relevante e duração elevada**, como vento, árvore ou vegetação e descarga atmosférica.

Dessa forma, os dados mostram que **frequência e tempo de solução são dimensões distintas das ocorrências**. A análise conjunta dessas dimensões permite identificar tanto as causas mais recorrentes quanto aquelas associadas aos atendimentos mais prolongados.
